create or replace function public.promo_evaluate_experiment()
returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_exp public.promo_experiment%rowtype;
begin
  select * into v_exp
  from public.promo_experiment
  where id = 1
  for update;

  if not found then
    return jsonb_build_object('status', 'missing');
  end if;

  if v_exp.status <> 'closed'
     and v_exp.estimated_spend_usd >= v_exp.spend_guard_usd then
    update public.promo_experiment
    set status = 'closed',
        closed_reason = 'cost_guard',
        updated_at = now()
    where id = 1;
  elsif v_exp.status <> 'closed'
        and now() >= v_exp.redeem_until then
    update public.promo_experiment
    set status = 'closed',
        closed_reason = 'redemption_window_ended',
        updated_at = now()
    where id = 1;
  elsif v_exp.status = 'active'
        and now() >= v_exp.expansion_check_at then
    if v_exp.estimated_spend_usd < v_exp.spend_guard_usd then
      update public.promo_experiment
      set status = 'expanded',
          current_cap = expanded_cap,
          updated_at = now()
      where id = 1;
    else
      update public.promo_experiment
      set status = 'closed',
          closed_reason = 'cost_guard',
          updated_at = now()
      where id = 1;
    end if;
  end if;

  select * into v_exp
  from public.promo_experiment
  where id = 1;

  return jsonb_build_object(
    'status', v_exp.status,
    'current_cap', v_exp.current_cap,
    'redeem_until', v_exp.redeem_until,
    'estimated_spend_usd', v_exp.estimated_spend_usd,
    'spend_guard_usd', v_exp.spend_guard_usd,
    'closed_reason', v_exp.closed_reason
  );
end;
$$;

create or replace function public.promo_redeem(
  p_user_id uuid,
  p_code text,
  p_utm_source text default null,
  p_utm_medium text default null,
  p_utm_campaign text default null,
  p_utm_content text default null
)
returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_exp public.promo_experiment%rowtype;
  v_code public.promo_codes%rowtype;
  v_existing public.promo_redemptions%rowtype;
  v_count integer := 0;
  v_expires_at timestamptz;
begin
  perform public.promo_evaluate_experiment();

  select * into v_exp
  from public.promo_experiment
  where id = 1
  for update;

  select * into v_code
  from public.promo_codes
  where code = upper(btrim(p_code))
    and enabled = true
    and experiment_id = 1;

  if not found then
    return jsonb_build_object('ok', false, 'reason', 'INVALID_CODE');
  end if;

  select * into v_existing
  from public.promo_redemptions
  where user_id = p_user_id
  limit 1;

  if found then
    return jsonb_build_object(
      'ok', false,
      'reason', 'ALREADY_USED',
      'code', v_existing.code,
      'cohort', v_existing.cohort,
      'expires_at', v_existing.expires_at
    );
  end if;

  if v_exp.status = 'closed' or now() >= v_exp.redeem_until then
    return jsonb_build_object(
      'ok', false,
      'reason', 'EXPIRED',
      'closed_reason', v_exp.closed_reason
    );
  end if;

  select count(*)::integer into v_count
  from public.promo_redemptions
  where code = v_code.code;

  if v_count >= v_exp.current_cap then
    return jsonb_build_object(
      'ok', false,
      'reason', 'CAP_REACHED',
      'review_at', v_exp.expansion_check_at,
      'status', v_exp.status
    );
  end if;

  v_expires_at := now() + interval '90 days';

  insert into public.promo_redemptions (
    experiment_id,
    code,
    cohort,
    user_id,
    redeemed_at,
    expires_at,
    utm_source,
    utm_medium,
    utm_campaign,
    utm_content
  )
  values (
    1,
    v_code.code,
    v_code.cohort,
    p_user_id,
    now(),
    v_expires_at,
    nullif(left(btrim(coalesce(p_utm_source, '')), 120), ''),
    nullif(left(btrim(coalesce(p_utm_medium, '')), 120), ''),
    nullif(left(btrim(coalesce(p_utm_campaign, '')), 120), ''),
    nullif(left(btrim(coalesce(p_utm_content, '')), 120), '')
  );

  return jsonb_build_object(
    'ok', true,
    'code', v_code.code,
    'cohort', v_code.cohort,
    'expires_at', v_expires_at
  );
exception
  when unique_violation then
    select * into v_existing
    from public.promo_redemptions
    where user_id = p_user_id
    limit 1;

    return jsonb_build_object(
      'ok', false,
      'reason', 'ALREADY_USED',
      'code', v_existing.code,
      'cohort', v_existing.cohort,
      'expires_at', v_existing.expires_at
    );
end;
$$;

create or replace function public.promo_record_ai_usage(
  p_user_id uuid,
  p_code text,
  p_task text,
  p_model text,
  p_prompt_tokens integer,
  p_output_tokens integer,
  p_thinking_tokens integer,
  p_estimated_cost_usd numeric
)
returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_code text := upper(btrim(coalesce(p_code, '')));
  v_cost numeric := greatest(coalesce(p_estimated_cost_usd, 0), 0);
  v_has_active_redemption boolean := false;
  v_state jsonb;
begin
  select exists (
    select 1
    from public.promo_redemptions
    where user_id = p_user_id
      and code = v_code
      and expires_at > now()
  )
  into v_has_active_redemption;

  if not v_has_active_redemption then
    return jsonb_build_object('ok', false, 'reason', 'NO_ACTIVE_PROMO');
  end if;

  insert into public.promo_ai_usage (
    experiment_id,
    code,
    user_id,
    task,
    model,
    prompt_tokens,
    output_tokens,
    thinking_tokens,
    estimated_cost_usd
  )
  values (
    1,
    v_code,
    p_user_id,
    left(coalesce(nullif(btrim(p_task), ''), 'unknown'), 80),
    left(coalesce(nullif(btrim(p_model), ''), 'unknown'), 80),
    greatest(coalesce(p_prompt_tokens, 0), 0),
    greatest(coalesce(p_output_tokens, 0), 0),
    greatest(coalesce(p_thinking_tokens, 0), 0),
    v_cost
  );

  update public.promo_experiment
  set estimated_spend_usd = estimated_spend_usd + v_cost,
      updated_at = now()
  where id = 1;

  v_state := public.promo_evaluate_experiment();

  return jsonb_build_object('ok', true, 'experiment', v_state);
end;
$$;

