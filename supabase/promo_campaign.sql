create extension if not exists pg_cron with schema pg_catalog;
grant usage on schema cron to postgres;
grant all privileges on all tables in schema cron to postgres;

create table public.promo_experiment (
  id smallint primary key default 1 check (id = 1),
  status text not null default 'active'
    check (status in ('active', 'expanded', 'closed')),
  launched_at timestamptz not null default now(),
  expansion_check_at timestamptz not null default (now() + interval '7 days'),
  redeem_until timestamptz not null default (now() + interval '30 days'),
  initial_cap integer not null default 20 check (initial_cap > 0),
  expanded_cap integer not null default 50 check (expanded_cap >= initial_cap),
  current_cap integer not null default 20 check (current_cap > 0),
  spend_guard_usd numeric(10, 6) not null default 7.500000
    check (spend_guard_usd > 0),
  estimated_spend_usd numeric(12, 6) not null default 0
    check (estimated_spend_usd >= 0),
  closed_reason text,
  updated_at timestamptz not null default now()
);

create table public.promo_codes (
  code text primary key,
  cohort text not null unique check (cohort in ('ore', 'inbde', 'adc')),
  experiment_id smallint not null default 1
    references public.promo_experiment(id) on delete cascade,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  check (code = upper(code))
);

create table public.promo_redemptions (
  id uuid primary key default gen_random_uuid(),
  experiment_id smallint not null default 1
    references public.promo_experiment(id) on delete cascade,
  code text not null references public.promo_codes(code),
  cohort text not null check (cohort in ('ore', 'inbde', 'adc')),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  redeemed_at timestamptz not null default now(),
  expires_at timestamptz not null,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  created_at timestamptz not null default now()
);

create index promo_redemptions_code_idx
  on public.promo_redemptions(code, redeemed_at);

create index promo_redemptions_expires_idx
  on public.promo_redemptions(expires_at);

create table public.promo_ai_usage (
  id bigint generated by default as identity primary key,
  experiment_id smallint not null default 1
    references public.promo_experiment(id) on delete cascade,
  code text not null references public.promo_codes(code),
  user_id uuid not null references auth.users(id) on delete cascade,
  task text not null,
  model text not null,
  prompt_tokens integer not null default 0 check (prompt_tokens >= 0),
  output_tokens integer not null default 0 check (output_tokens >= 0),
  thinking_tokens integer not null default 0 check (thinking_tokens >= 0),
  estimated_cost_usd numeric(12, 8) not null default 0
    check (estimated_cost_usd >= 0),
  created_at timestamptz not null default now()
);

create index promo_ai_usage_code_created_idx
  on public.promo_ai_usage(code, created_at);

create index promo_ai_usage_user_created_idx
  on public.promo_ai_usage(user_id, created_at);

